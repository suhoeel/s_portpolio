## RRF의 세 가지 장점

1. **점수 정규화가 필요 없다**: 점수 범위가 어떻게 다르든 상관없이 등수만 따지므로 견고합니다.
2. **튜닝 스트레스가 없다**: 별도의 머신러닝 가중치 학습 없이 상수 `k=60` 하나만으로 프로덕션 환경에서 매우 우수한 품질을 냅니다.
3. **새로운 검색 모델을 추가하기 쉽다**: 나중에 3번째, 4번째 검색 모델이 추가되어도 단순히 `+ 1 / (60 + 새 모델 등수)`만 더해주면 끝납니다.

